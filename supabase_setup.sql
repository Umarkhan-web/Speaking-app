-- 1. FOYDALANUVCHILAR PROFILLARI (profiles)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  email TEXT,
  name TEXT,
  avatar_url TEXT,
  xp INTEGER DEFAULT 0,
  level INTEGER DEFAULT 2,
  target_band NUMERIC DEFAULT 6.5,
  settings JSONB DEFAULT '{}'::jsonb,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Foydalanuvchilar o'z profilini ko'ra oladi" 
ON public.profiles FOR SELECT 
USING (auth.uid() = id);

CREATE POLICY "Foydalanuvchilar o'z profilini tahrirlay oladi" 
ON public.profiles FOR ALL 
USING (auth.uid() = id);

-- 2. MASHQLAR VA IELTS NATIJALARI (speaking_sessions)
CREATE TABLE IF NOT EXISTS public.speaking_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  topic_en TEXT,
  topic_uz TEXT,
  duration NUMERIC,
  transcript TEXT,
  overall_score INTEGER,
  ielts_band TEXT,
  vocabulary_level TEXT,
  fluency_score INTEGER,
  scores JSONB DEFAULT '{}'::jsonb,
  grammar_errors JSONB DEFAULT '[]'::jsonb,
  vocabulary_suggestions JSONB DEFAULT '[]'::jsonb,
  summary TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.speaking_sessions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Foydalanuvchilar o'z mashqlarini ko'ra oladi" 
ON public.speaking_sessions FOR SELECT 
USING (auth.uid() = user_id);

CREATE POLICY "Foydalanuvchilar o'z mashqlarini qo'sha oladi" 
ON public.speaking_sessions FOR INSERT 
WITH CHECK (auth.uid() = user_id);

-- 3. SAQLANGAN LUG'AT DAFTARCHASI (vocab_notebook)
CREATE TABLE IF NOT EXISTS public.vocab_notebook (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  word TEXT NOT NULL,
  meaning TEXT,
  example TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE(user_id, word)
);

ALTER TABLE public.vocab_notebook ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Foydalanuvchilar o'z so'zlarini ko'ra oladi" 
ON public.vocab_notebook FOR SELECT 
USING (auth.uid() = user_id);

CREATE POLICY "Foydalanuvchilar o'z so'zlarini boshqara oladi" 
ON public.vocab_notebook FOR ALL 
USING (auth.uid() = user_id);
